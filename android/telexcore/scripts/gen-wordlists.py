#!/usr/bin/env python3
"""Regenerate EnglishWordLists.kt from the Swift sources (single source of truth).
Run from anywhere:  python3 android/telexcore/scripts/gen-wordlists.py
"""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, "..", "..", ".."))
src = os.path.join(root, "TelexCore", "Sources", "TelexCore")
out = os.path.join(here, "..", "src", "main", "kotlin", "com", "viettelex", "telexcore", "EnglishWordLists.kt")

def blocks(text):
    return re.findall(r'"""\n(.*?)"""', text, re.S)

def words(block):
    return [w for w in re.split(r"[ \n]+", block) if w]

def section(text, start, end):
    i = text.index(start)
    j = text.index(end, i + len(start)) if end else len(text)
    return text[i:j]

coll = open(os.path.join(src, "EnglishCollisions.swift")).read()
frz = open(os.path.join(src, "EnglishFreezePrefixes.swift")).read()
ctx = open(os.path.join(src, "EnglishContextWords.swift")).read()
common_src = open(os.path.join(src, "CommonSyllables.swift")).read()
common = [w for b in blocks(section(common_src, "private static let data", None)) for w in words(b)]
assert common == sorted(common) and common

collisions = [w for b in blocks(section(coll, "private static let list", None)) for w in words(b)]
freeze = [w for b in blocks(section(frz, "private static let data", None)) for w in words(b)]
freeze_min = re.search(r"static let minLength = (\d+)", frz).group(1)
freeze_max = re.search(r"static let maxLength = (\d+)", frz).group(1)
assert freeze == sorted(freeze) and freeze
neutral = [w for b in blocks(section(ctx, "static let neutralLoanwords", "static let maxLength")) for w in words(b)]
ctxwords = [w for b in blocks(section(ctx, "private static let wordList", "private static let restoreOnlyList")) for w in words(b)]
restore = [w for b in blocks(section(ctx, "private static let restoreOnlyList", None)) for w in words(b)]
maxlen = re.search(r"static let maxLength = (\d+)", ctx).group(1)
function = [w for b in blocks(section(ctx, "static let functionWords", "static let predecessorGates")) for w in words(b)]
tails = [w for b in blocks(section(ctx, "static let contractionTails", "static let runKeepers")) for w in words(b)]
keepers = [w for b in blocks(section(ctx, "static let runKeepers", "static let codeAcronyms")) for w in words(b)]
acronyms = [w for b in blocks(section(ctx, "static let codeAcronyms", "private static func parseGates")) for w in words(b)]
assert acronyms and all(re.fullmatch(r"[a-z]{2,4}", w) for w in acronyms)
gates = []
for b in blocks(section(ctx, "static let predecessorGates", "static let contractionTails")):
    for line in b.split("\n"):
        if ":" not in line: continue
        w, preds = line.split(":", 1)
        gates.append((w.strip(), words(preds.strip())))
assert function and tails and keepers and gates and len(gates) <= 8
# Retroactive English: class letters in bit order (RetroEnglish.classLetters) + `X: words` lines.
class_letters = re.findall(r'"(\w)"', re.search(r"static let classLetters: \[Character\] = \[(.*?)\]",
                           open(os.path.join(src, "RetroEnglish.swift")).read()).group(1))
retro = []
for b in blocks(section(ctx, "static let retroClassList", "static let retroClasses")):
    for line in b.split("\n"):
        if ":" not in line: continue
        letter, ws = line.split(":", 1)
        retro.append((class_letters.index(letter.strip()), words(ws.strip())))
assert retro and len(class_letters) <= 8

# Frequency table (EnglishFrequency.swift, Scripts/gen-english-frequency.py): words "w=EEVV" + pairs.
freq_src = open(os.path.join(src, "EnglishFrequency.swift")).read()
freq_words = [w for b in blocks(section(freq_src, "private static let words", "private static let pairs")) for w in words(b)]
freq_pairs = [w for b in blocks(section(freq_src, "private static let pairs", "static func scores")) for w in words(b)]
freq_strong = re.search(r"static let strongMin: UInt8 = (\d+)", freq_src).group(1)
freq_maxw = re.search(r"static let maxWordLength = (\d+)", freq_src).group(1)
freq_maxp = re.search(r"static let maxPairLength = (\d+)", freq_src).group(1)
assert int(re.search(r"static let wordCount = (\d+)", freq_src).group(1)) == len(freq_words)
assert int(re.search(r"static let pairCount = (\d+)", freq_src).group(1)) == len(freq_pairs)
assert all(re.fullmatch(r"[a-z]+=[0-9a-f]{4}", w) for w in freq_words)
assert all(re.fullmatch(r"[a-z]+>[a-z]+", w) for w in freq_pairs)
_fk = [w.split("=")[0].encode() for w in freq_words]
assert _fk == sorted(_fk) and len(set(_fk)) == len(_fk)
assert [w.encode() for w in freq_pairs] == sorted(w.encode() for w in freq_pairs)

def lit(ws):
    lines, cur = [], ""
    for w in ws:
        if len(cur) + len(w) + 1 > 90:
            lines.append(cur); cur = ""
        cur = (cur + " " + w) if cur else w
    if cur: lines.append(cur)
    return "\n".join(lines)

with open(out, "w") as f:
    f.write("// GENERATED by android/telexcore/scripts/gen-wordlists.py from\n")
    f.write("// TelexCore/Sources/TelexCore/EnglishCollisions.swift + EnglishContextWords.swift\n")
    f.write("// (+ EnglishFreezePrefixes, CommonSyllables, EnglishFrequency).\n")
    f.write("// DO NOT EDIT — edit the Swift source and regenerate.\n")
    f.write("package com.viettelex.telexcore\n\n")
    f.write("internal object EnglishCollisions {\n")
    f.write("    val words = WordSet(parseWords(LIST))\n")
    f.write('    private const val LIST = """\n' + lit(collisions) + '\n"""\n}\n\n')
    f.write("internal object EnglishContextWords {\n")
    f.write("    val words = WordSet(parseWords(WORDS))\n")
    f.write("    val restoreOnly = WordSet(parseWords(RESTORE_ONLY))\n")
    f.write("    val neutralLoanwords = WordSet(parseWords(NEUTRAL))\n")
    f.write("    /** Function words: open an English run on their own (see EnglishContextWords.swift). */\n")
    f.write("    val functionWords = WordSet(parseWords(FUNCTION))\n")
    f.write("    /** Contraction tails left by the apostrophe boundary (I've → ve): neutral. */\n")
    f.write("    val contractionTails = WordSet(parseWords(CONTRACTION_TAILS))\n")
    f.write("    /** Run keepers (box→bõ, car→cả): stay Vietnamese but do not end an English run. */\n")
    f.write("    val runKeepers = WordSet(parseWords(RUN_KEEPERS))\n")
    f.write("    /** Code acronyms (MaxID, TaxURL): an uppercase run that is NOT a name's initials. */\n")
    f.write("    val codeAcronyms = WordSet(parseWords(CODE_ACRONYMS))\n")
    f.write("    /** Predecessor gates: gateWords[i] restores in a run only right after gatePredecessors[i]. */\n")
    f.write("    val gateWords: Array<String> = arrayOf(" + ", ".join('"%s"' % w for w, _ in gates) + ")\n")
    f.write("    val gatePredecessors: Array<WordSet> = arrayOf(\n")
    for _, ps in gates:
        f.write('        WordSet(parseWords("' + " ".join(ps) + '")),\n')
    f.write("    )\n")
    f.write(f"    const val maxLength = {maxlen}\n")
    f.write("    /** Retroactive English word classes (EnglishContextWords.retroClassList): word → bits. */\n")
    f.write("    val retroClasses: HashMap<String, Int> = HashMap<String, Int>(256).also { m ->\n")
    for bit, ws in retro:
        f.write(f'        for (w in parseWords("{" ".join(ws)}")) m[w] = (m[w] ?: 0) or {1 << bit}\n')
    f.write("    }\n")
    f.write('    private const val WORDS = """\n' + lit(ctxwords) + '\n"""\n')
    f.write('    private const val RESTORE_ONLY = """\n' + lit(restore) + '\n"""\n')
    f.write('    private const val FUNCTION = """\n' + lit(function) + '\n"""\n')
    f.write('    private const val CONTRACTION_TAILS = """\n' + lit(tails) + '\n"""\n')
    f.write('    private const val RUN_KEEPERS = """\n' + lit(keepers) + '\n"""\n')
    f.write('    private const val CODE_ACRONYMS = """\n' + lit(acronyms) + '\n"""\n')
    f.write('    private const val NEUTRAL = """\n' + lit(neutral) + '\n"""\n}\n\n')
    f.write("/**\n")
    f.write(" * API công khai (bàn phím — gõ vuốt, giai đoạn 3): phân loại MỘT từ đã chốt theo cùng\n")
    f.write(" * bảng với `contextualEnglish` (port iOS EnglishContextLookup). Chữ thường ASCII.\n")
    f.write(" */\n")
    f.write("object EnglishContextLookup {\n")
    f.write("    fun opensEnglishRun(w: String): Boolean = EnglishContextWords.words.contains(w)\n")
    f.write("    fun isNeutralLoanword(w: String): Boolean = EnglishContextWords.neutralLoanwords.contains(w)\n")
    f.write("    /** Từ chức năng: một mình đủ mở mạch tiếng Anh trong engine. */\n")
    f.write("    fun isFunctionWord(w: String): Boolean = EnglishContextWords.functionWords.contains(w)\n")
    f.write("}\n\n")
    f.write("/**\n")
    f.write(" * Eager English restore (EnglishFreezePrefixes.swift): raw prefixes, sorted, at which an\n")
    f.write(" * English word freezes with marks on screen. Binary search IN the constant string —\n")
    f.write(" * no set is built, nothing allocated; probed once per word at the freeze moment.\n")
    f.write(" */\n")
    f.write("internal object EnglishFreezePrefixes {\n")
    f.write(f"    const val minLength = {freeze_min}\n")
    f.write(f"    const val maxLength = {freeze_max}\n")
    f.write(f"    const val count = {len(freeze)}\n")
    f.write("    private fun isSep(c: Char) = c == ' ' || c == '\\n'\n")
    f.write("    /** raw[0 until n] (ascii codes, any case) is in the table. */\n")
    f.write("    fun contains(raw: IntArray, n: Int): Boolean {\n")
    f.write("        if (n < minLength || n > maxLength || n > raw.size) return false\n")
    f.write("        val buf = DATA\n")
    f.write("        var lo = 0\n        var hi = buf.length\n")
    f.write("        while (lo < hi) {\n")
    f.write("            var s = (lo + hi) / 2\n")
    f.write("            while (s > lo && !isSep(buf[s - 1])) s--\n")
    f.write("            if (isSep(buf[s])) {\n")
    f.write("                var t = s\n")
    f.write("                while (t < hi && isSep(buf[t])) t++\n")
    f.write("                if (t >= hi) { hi = s; continue }\n")
    f.write("                s = t\n")
    f.write("            }\n")
    f.write("            var e = s\n")
    f.write("            while (e < buf.length && !isSep(buf[e])) e++\n")
    f.write("            var cmp = 0\n            var i = 0\n")
    f.write("            while (i < n && s + i < e) {\n")
    f.write("                var k = raw[i]\n")
    f.write("                if (k in 0x41..0x5A) k = k or 0x20\n")
    f.write("                val b = buf[s + i].code\n")
    f.write("                if (b != k) { cmp = if (b < k) -1 else 1; break }\n")
    f.write("                i++\n")
    f.write("            }\n")
    f.write("            if (cmp == 0) {\n")
    f.write("                val tl = e - s\n")
    f.write("                if (tl == n) return true\n")
    f.write("                cmp = if (tl < n) -1 else 1\n")
    f.write("            }\n")
    f.write("            if (cmp < 0) lo = e else hi = s\n")
    f.write("        }\n")
    f.write("        return false\n")
    f.write("    }\n")
    f.write('    private const val DATA = """\n' + lit(freeze) + '\n"""\n}\n\n')
    f.write("/**\n")
    f.write(" * Common Vietnamese syllables (CommonSyllables.swift, Scripts/gen-common-syllables.py):\n")
    f.write(" * Telex keys, tone last (\"vieetj\", \"hoaf\"). Acronym + typo rules, boundary-only.\n")
    f.write(" */\n")
    f.write("internal object CommonSyllables {\n")
    f.write("    val keys = WordSet(parseWords(DATA))\n")
    f.write(f"    const val count = {len(common)}\n")
    f.write('    private const val DATA = """\n' + lit(common) + '\n"""\n}\n\n')
    f.write("/**\n")
    f.write(" * English vs Vietnamese frequency (EnglishFrequency.swift, Scripts/gen-english-frequency.py):\n")
    f.write(" * both on ONE log scale 0–255 (10× ≈ 45), plus frequent Vietnamese syllable pairs. Statistics\n")
    f.write(" * derived from CC BY-SA 4.0 / CC BY 3.0 / CC BY 2.0 FR data — attribution: docs/DATA-SOURCES.md.\n")
    f.write(" * Binary search IN the constant strings (no set built, nothing allocated); boundary-only.\n")
    f.write(" */\n")
    f.write("internal object EnglishFrequency {\n")
    f.write(f"    const val strongMin = {freq_strong}\n")
    f.write(f"    const val maxWordLength = {freq_maxw}\n")
    f.write(f"    const val maxPairLength = {freq_maxp}\n")
    f.write(f"    const val wordCount = {len(freq_words)}\n")
    f.write(f"    const val pairCount = {len(freq_pairs)}\n")
    f.write("    /** Packed scores: English frequency. */\n")
    f.write("    fun en(packed: Int): Int = packed ushr 8\n")
    f.write("    /** Packed scores: Vietnamese frequency (0 = no Vietnamese reading). */\n")
    f.write("    fun vn(packed: Int): Int = packed and 0xFF\n")
    f.write("    /** (en shl 8 or vn) of lowercase a–z key[0 until n], or -1 if absent. */\n")
    f.write("    fun scores(key: IntArray, n: Int): Int {\n")
    f.write("        if (n < 1 || n > maxWordLength || n > key.size) return -1\n")
    f.write("        val s = find(WORDS, n, '=') { key[it] }\n")
    f.write("        return if (s < 0) -1 else packed(s + n + 1)\n")
    f.write("    }\n")
    f.write("    /** Same for a lowercase word. */\n")
    f.write("    fun scores(w: String): Int {\n")
    f.write("        val n = w.length\n")
    f.write("        if (n < 1 || n > maxWordLength) return -1\n")
    f.write("        val s = find(WORDS, n, '=') { w[it].code }\n")
    f.write("        return if (s < 0) -1 else packed(s + n + 1)\n")
    f.write("    }\n")
    f.write("    /** \"english>telexKey\" key[0 until n] (\">\" included) is in PAIRS. */\n")
    f.write("    fun hasPair(key: IntArray, n: Int): Boolean {\n")
    f.write("        if (n < 3 || n > maxPairLength || n > key.size) return false\n")
    f.write("        return find(PAIRS, n, ' ') { key[it] } >= 0\n")
    f.write("    }\n")
    f.write("    private fun nib(c: Char): Int = if (c <= '9') c - '0' else c - 'a' + 10\n")
    f.write("    private fun packed(i: Int): Int =\n")
    f.write("        ((nib(WORDS[i]) shl 4 or nib(WORDS[i + 1])) shl 8) or (nib(WORDS[i + 2]) shl 4 or nib(WORDS[i + 3]))\n")
    f.write("    private fun isSep(c: Char) = c == ' ' || c == '\\n'\n")
    f.write("    /** Start of the token whose head (up to [sep]; whole token when sep = ' ') equals key[0 until n], or -1. */\n")
    f.write("    private inline fun find(buf: String, n: Int, sep: Char, key: (Int) -> Int): Int {\n")
    f.write("        var lo = 0\n        var hi = buf.length\n")
    f.write("        while (lo < hi) {\n")
    f.write("            var s = (lo + hi) / 2\n")
    f.write("            while (s > lo && !isSep(buf[s - 1])) s--\n")
    f.write("            if (isSep(buf[s])) {\n")
    f.write("                var t = s\n")
    f.write("                while (t < hi && isSep(buf[t])) t++\n")
    f.write("                if (t >= hi) { hi = s; continue }\n")
    f.write("                s = t\n")
    f.write("            }\n")
    f.write("            var e = s\n")
    f.write("            while (e < buf.length && !isSep(buf[e])) e++\n")
    f.write("            var k = e\n")
    f.write("            if (sep != ' ') { k = s; while (k < e && buf[k] != sep) k++ }\n")
    f.write("            var cmp = 0\n            var i = 0\n")
    f.write("            while (i < n && s + i < k) {\n")
    f.write("                val a = buf[s + i].code\n")
    f.write("                val b = key(i)\n")
    f.write("                if (a != b) { cmp = if (a < b) -1 else 1; break }\n")
    f.write("                i++\n")
    f.write("            }\n")
    f.write("            if (cmp == 0) {\n")
    f.write("                val tl = k - s\n")
    f.write("                if (tl == n) return s\n")
    f.write("                cmp = if (tl < n) -1 else 1\n")
    f.write("            }\n")
    f.write("            if (cmp < 0) lo = e else hi = s\n")
    f.write("        }\n")
    f.write("        return -1\n")
    f.write("    }\n")
    f.write('    private const val WORDS = """\n' + lit(freq_words) + '\n"""\n')
    f.write('    private const val PAIRS = """\n' + lit(freq_pairs) + '\n"""\n}\n\n')
    f.write("internal fun parseWords(list: String): HashSet<String> {\n")
    f.write("    val set = HashSet<String>(1024)\n")
    f.write("    var i = 0\n    val n = list.length\n")
    f.write("    while (i < n) {\n")
    f.write("        while (i < n && (list[i] == ' ' || list[i] == '\\n')) i++\n")
    f.write("        val s = i\n")
    f.write("        while (i < n && list[i] != ' ' && list[i] != '\\n') i++\n")
    f.write("        if (i > s) set.add(list.substring(s, i))\n")
    f.write("    }\n    return set\n}\n")
print(len(freq_words), len(freq_pairs), len(freeze), len(collisions), len(ctxwords), len(restore), len(neutral), len(function), len(tails), len(keepers), gates)
