#!/bin/sh
# gen-seed-next.sh — bảng TỪ KẾ TIẾP SEED cho gợi ý từ trên máy tính (macOS / Linux / Windows),
# sinh THẲNG từ mã iOS: UserLangModel mới (chỉ có seed — như người dùng iOS vừa cài) +
# SeedData.unigrams/bigrams + UserLangModel.seedNext, rồi `nextWords(after: prev, limit: 24)`
# cho mọi prev có seed. Thứ tự = đúng thứ tự thanh gợi ý iOS cho người dùng mới (nội suy
# λ_bi·P_bi + 0.1·P_uni + (1−λ_bi)·0.9·P_seed, lọc "suggestable" bằng VNSuggest.contains) —
# docs: iOS/docs/IOS-SUGGESTIONS.md tầng 2/3.
#
# Ra hai file (KHÔNG sửa tay):
#   App/Sources/SeedNextData.swift   — macOS + Linux (symlink linux/engine-capi/Sources/TextToolCLI)
#   windows/app/core/seed_next.inc   — Windows (word_prediction.cpp)
# Máy tính không liên kết UserLangModel (lưu file/di trú/codec) hay literal SeedData.bigrams —
# chỉ bảng chữ đã xếp sẵn này (~4,7 KB).
#
#   Scripts/gen-seed-next.sh           (macOS, cần swiftc; ghi hai file)
#   Scripts/gen-seed-next.sh --check   (so với file đã commit; khác ⇒ exit 1)
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
KB="$ROOT/iOS/Keyboard"
SWIFT_OUT="$ROOT/App/Sources/SeedNextData.swift"
INC_OUT="$ROOT/windows/app/core/seed_next.inc"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
# performExpiringActivity không có trên macOS — chỉ đường lưu file dùng, ở đây không chạy.
sed 's/ProcessInfo\.processInfo\.performExpiringActivity(/_genShimExpiring(/' "$KB/UserLangModel.swift" > "$TMP/UserLangModel.swift"
cat > "$TMP/main.swift" <<'SWIFT'
import Foundation
func _genShimExpiring(withReason: String, using b: @escaping (Bool) -> Void) { b(false) }
// = KeyboardViewController.langModel (người dùng mới): chỉ seed.
let m = UserLangModel(appGroup: nil)
m.isKnownWord = { VNSuggest.contains($0) }
m.seedIfEmpty(unigrams: SeedData.unigrams, bigrams: SeedData.bigrams)
var keys = Set(SeedData.bigrams.map { $0.0 })
keys.formUnion(UserLangModel.seedNext.keys)
var rows: [String] = []
for k in keys.sorted(by: { Array($0.utf8).lexicographicallyPrecedes(Array($1.utf8)) }) {
    precondition(!k.contains(" ") && k == k.lowercased() && k == k.precomposedStringWithCanonicalMapping)
    let next = m.nextWords(after: k, limit: 24)
    if !next.isEmpty { rows.append(([k] + next).joined(separator: " ")) }
}
let text = rows.joined(separator: "\n")
let bytes = text.utf8.count + 1
var swift = """
// SeedNextData.swift — GENERATED by Scripts/gen-seed-next.sh from iOS UserLangModel + SeedData
// (người dùng iOS mới: chỉ seed). KHÔNG sửa tay. \(rows.count) dòng, \(bytes) byte chữ.
// Mỗi dòng: "<prev> <từ kế tiếp…>" theo đúng thứ tự UserLangModel.nextWords(after: prev,
// limit: 24); dòng sắp theo byte UTF-8 của prev. Dùng: WordPrediction.swift (SeedNext).
enum SeedNextData {
    static let packed = \"\"\"

"""
for r in rows { swift += "    " + r + "\n" }
swift += "    \"\"\"\n\n"
swift += "    /// `packed` → [prev: từ kế tiếp] — gọi lười (gợi ý từ bật), không giữ khi tắt.\n"
swift += "    static func table() -> [String: [String]] {\n"
swift += "        var t: [String: [String]] = [:]\n"
swift += "        for line in packed.split(separator: \"\\n\") {\n"
swift += "            let f = line.split(separator: \" \").map(String.init)\n"
swift += "            if f.count > 1 { t[f[0]] = Array(f.dropFirst()) }\n"
swift += "        }\n"
swift += "        return t\n"
swift += "    }\n}\n"
try! swift.write(toFile: CommandLine.arguments[1], atomically: true, encoding: .utf8)

var inc = "// GENERATED by Scripts/gen-seed-next.sh (= App/Sources/SeedNextData.swift). Do not edit.\n"
inc += "// \(rows.count) rows \"<prev> <next words…>\\n\" sorted by the UTF-8 bytes of prev, \(bytes) bytes.\n"
inc += "constexpr int kSeedNextCount = \(rows.count);\n"
inc += "const char kSeedNextText[] =\n"
var offs: [Int] = [], off = 0
for r in rows {
    offs.append(off)
    off += r.utf8.count + 1
    inc += "    \"" + r + "\\n\"\n"
}
inc += "    ;\n"
precondition(off <= 0xFFFF)
inc += "const uint16_t kSeedNextOff[] = {\n"
for i in stride(from: 0, to: offs.count, by: 16) {
    inc += "    " + offs[i..<min(i + 16, offs.count)].map(String.init).joined(separator: ", ") + ",\n"
}
inc += "};\n"
try! inc.write(toFile: CommandLine.arguments[2], atomically: true, encoding: .utf8)
SWIFT
swiftc -O -o "$TMP/gen" "$TMP/main.swift" "$TMP/UserLangModel.swift" "$KB/UserLMTables.swift" "$KB/SeedData.swift" \
  "$KB/VNSuggest.swift" "$KB/VNLexicon2.swift" "$KB/SyllableLM.swift" "$KB/SwipeLexicon.swift" \
  "$ROOT/iOS/Shared/AppFlavor.swift"
# VNLexicon2Data đọc vnlexicon.bin cạnh executable (Bundle.main của công cụ dòng lệnh).
cp "$KB/Resources/vnlexicon.bin" "$TMP/"
"$TMP/gen" "$TMP/SeedNextData.swift" "$TMP/seed_next.inc"
if [ "${1:-}" = "--check" ]; then
  cmp -s "$TMP/SeedNextData.swift" "$SWIFT_OUT" && cmp -s "$TMP/seed_next.inc" "$INC_OUT" \
    || { echo "seed next tables are stale: run Scripts/gen-seed-next.sh" >&2; exit 1; }
  echo "seed next tables up to date"
else
  cp "$TMP/SeedNextData.swift" "$SWIFT_OUT"
  cp "$TMP/seed_next.inc" "$INC_OUT"
  echo "wrote $SWIFT_OUT and $INC_OUT"
fi
